/**
 * Helper to compute dates relative to today (2026-10-20) so the calendar
 * and daily study planner always have realistic scheduled tasks right out of the box.
 */
export function getFormattedDateOffset(daysOffset: number): string {
  const base = new Date();
  base.setDate(base.getDate() + daysOffset);
  const year = base.getFullYear();
  const month = String(base.getMonth() + 1).padStart(2, '0');
  const day = String(base.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

